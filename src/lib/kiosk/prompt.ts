export function buildUserText(req: KioskGuideRequest): string {
  const lines = [`어르신의 목표: ${req.goal}`];

  if (req.history.length > 0) {
    lines.push("", "지금까지 드린 안내 (오래된 것부터):");
    req.history.forEach((h, i) => lines.push(`${i + 1}. ${h.speech}`));
  } else {
    lines.push("", "첫 안내입니다.");
  }

  if (req.userReply) {
    lines.push("", `어르신의 대답: ${req.userReply}`);
  }

  lines.push("", "사진은 지금 화면입니다. 다음에 할 일 하나를 안내해 주세요.");
  return lines.join("\n");
}
